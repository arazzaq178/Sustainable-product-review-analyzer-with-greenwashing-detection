@app.post("/analyze/text", response_model=AnalysisResponse)
async def analyze_text(request: TextAnalysisRequest):
    """
    Analyzes review text for greenwashing indicators.

    Input: Product review text
    Output: Greenwashing score + detailed breakdown
    """

    if not models.loaded:
        raise HTTPException(status_code=503, detail="Models not loaded yet")

    try:
        # Preprocess text
        processed = models.preprocessor.process(request.text)

        # NLP Analysis
        nlp_results = models.nlp_trainer.predict([request.text])[0]
        nlp_output = {
            **nlp_results,
            'eco_score': processed['eco_score'],
            'keyword_count': processed['keyword_count'],
            'has_certification': processed['has_certification'],
            'has_contradiction': processed['has_contradiction'],
            'vague_claim_count': processed['vague_claim_count'],
            'sentiment_score': nlp_results.get('sentiment_score', 0)
        }

        # RNN Analysis (if history provided)
        rnn_output = None
        if request.review_history:
            ratings = [r.get('rating', 3) for r in request.review_history]
            eco_scores = [r.get('eco_score', 0) for r in request.review_history]

            rnn_results = models.rnn_trainer.predict_trust_score([{
                'ratings': ratings,
                'eco_scores': eco_scores
            }])
            rnn_output = rnn_results[0] if rnn_results else None

        # Final prediction
        final_result = models.ensemble.predict(
            nlp_output=nlp_output,
            cnn_output=None,
            rnn_output=rnn_output
        )

        return AnalysisResponse(
            greenwashing_score=final_result['greenwashing_score'],
            greenwashing_percentage=final_result['greenwashing_percentage'],
            classification=final_result['classification'],
            verdict=final_result['verdict'],
            risk_level=final_result['risk_level'],
            confidence=final_result['confidence'],
            eco_score=final_result['eco_score'],
            sentiment_score=float(nlp_output.get('sentiment_score', 0)),
            sustainability_keywords=int(processed['keyword_count']),
            has_certification=bool(processed['has_certification']),
            module_breakdown=final_result['module_breakdown'],
            explanation=final_result['explanation']
        )

    except Exception as e:
        logger.error(f"Text analysis error: {e}")
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/analyze/image")
async def analyze_image(file: UploadFile = File(...)):
    """
    Analyzes product image for eco-friendly packaging.

    Accepts: JPG, PNG, WEBP images
    Returns: Packaging classification + eco probability
    """

    if not models.loaded:
        raise HTTPException(status_code=503, detail="Models not loaded yet")

    # Validate file type
    if not file.content_type.startswith('image/'):
        raise HTTPException(status_code=400, detail="File must be an image")

    try:
        # Read image
        image_bytes = await file.read()
        image = Image.open(io.BytesIO(image_bytes))

        # CNN Prediction
        result = models.cnn_trainer.predict_image(image)

        return {
            "class": result['class'],
            "is_eco_friendly": result['is_eco_friendly'],
            "eco_probability": result['eco_probability'],
            "non_eco_probability": result['non_eco_probability'],
            "confidence": result['confidence'],
            "recommendation": (
                "✅ Eco-friendly packaging detected" if result['is_eco_friendly']
                else "⚠️ Non-eco packaging detected. Verify sustainability claims."
            )
        }

    except Exception as e:
        logger.error(f"Image analysis error: {e}")
        raise HTTPException(status_code=500, detail=str(e))


@app.post("/analyze/full")
async def analyze_full(
    text: str,
    file: Optional[UploadFile] = File(None),
    review_history: Optional[str] = None
):
    """
    Full analysis combining text + image + history.

    This is the main endpoint for complete greenwashing detection.
    """

    if not models.loaded:
        raise HTTPException(status_code=503, detail="Models not loaded yet")

    results = {}

    # Text Analysis
    text_request = TextAnalysisRequest(text=text)
    text_result = await analyze_text(text_request)
    results['text_analysis'] = text_result

    # Image Analysis (optional)
    if file:
        image_result = await analyze_image(file)
        results['image_analysis'] = image_result

    # Final Score
    nlp_prob = text_result.greenwashing_score
    cnn_prob = 1 - results.get('image_analysis', {}).get('eco_probability', 0.5)

    final_score = 0.6 * nlp_prob + 0.4 * cnn_prob if file else nlp_prob

    results['final_greenwashing_score'] = round(final_score, 4)
    results['final_verdict'] = (
        "🚨 HIGH GREENWASHING RISK" if final_score > 0.7
        else "⚠️ MODERATE RISK" if final_score > 0.4
        else "✅ LIKELY GENUINE ECO-FRIENDLY"
    )

    return results





